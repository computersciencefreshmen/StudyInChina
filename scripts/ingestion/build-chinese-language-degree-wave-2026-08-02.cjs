function program({
  id,
  institutionSlug,
  name,
  level,
  officialUrl,
  sourceTitle,
  teachingLanguage = null,
  duration = null,
  tuition = null,
  deadline = null,
  opensOn = null,
  applicationUrl = null,
  additionalEvidence = [],
  summary = null,
  riskFlags = [],
}) {
  const candidateId = `chinese-degree-${id}`
  const isLanguage = level === 'language'
  const genericSummary = {
    en: `The official source explicitly offers ${name.en} to international applicants. ${deadline ? `The 2026 application deadline of ${deadline} is closed; no later cycle is inferred.` : 'Current dates not stated by the source are not inferred.'}`,
    zh: `官方来源明确面向国际申请人开设${name.zh}。${deadline ? `2026年截止日为${deadline}，当前已结束；不推定下一周期。` : '官方未说明的当期日期不作推定。'}`,
    ru: `Официальный источник прямо предлагает иностранным абитуриентам программу «${name.ru}». ${deadline ? `Срок подачи в 2026 году (${deadline}) закрыт; следующий цикл не предполагается.` : 'Не опубликованные источником текущие сроки не предполагаются.'}`,
  }
  return {
    candidateId,
    candidateIds: [candidateId],
    institutionSlug,
    name,
    programType: isLanguage ? 'language' : 'degree',
    level,
    teachingLanguage: teachingLanguage
      ? { value: teachingLanguage, status: 'known' }
      : { value: null, status: 'officially_not_announced' },
    duration: duration
      ? { value: duration, status: 'known' }
      : { value: null, status: 'officially_not_announced' },
    tuition: tuition
      ? { ...tuition, currency: 'CNY', status: 'known' }
      : { amount: null, period: null, currency: 'CNY', status: 'officially_not_announced' },
    cycles: deadline ? closedCycle(deadline, opensOn) : [],
    evidence: {
      officialUrl,
      sourceTitle,
      checkedAt,
      summary: summary ?? genericSummary,
    },
    additionalEvidence: additionalEvidence.map((item) => ({ ...item, checkedAt })),
    applicationUrl,
    recommendedAction: 'publish_program_identity_without_open_cycle',
    qualityTier: 'A',
    riskFlags: [...new Set([
      ...(deadline ? ['2026_application_cycle_closed'] : ['current_cycle_not_announced']),
      ...riskFlags,
    ])],
    sourceFiles: [sourceFile],
  }
}

function scholarship({
  id,
  institutionSlug,
  name,
  programCandidateIds,
  officialUrl,
  sourceTitle,
  tiers,
  summary,
  applicableLevels,
  additionalEvidence = [],
}) {
  const candidateId = `chinese-scholarship-${id}`
  return {
    candidateId,
    candidateIds: [candidateId],
    institutionSlug,
    name,
    scholarshipType: 'other',
    scope: 'Verified international Chinese-language degree routes at the named host university.',
    applicableLevels,
    funding: {
      status: tiers.length ? 'known' : 'officially_not_announced',
      tiers,
    },
    cycles: [],
    evidence: {
      officialUrl,
      sourceTitle,
      checkedAt,
      summary,
    },
    additionalEvidence: additionalEvidence.map((item) => ({ ...item, checkedAt })),
    recommendedAction: 'publish_scholarship_identity_without_open_cycle',
    qualityTier: 'A',
    riskFlags: ['2026_degree_application_closed', 'next_degree_cycle_not_announced'],
    sourceFiles: [sourceFile],
    programCandidateIds: programCandidateIds.map((idValue) => `chinese-degree-${idValue}`),
  }
}

